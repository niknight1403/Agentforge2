import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import path from 'node:path';

const MAX_INFO_BYTES = 64 * 1024;

function fail(code, message) {
  const error = new Error(message);
  error.code = code;
  return error;
}

function requireAbsoluteExecutable(value) {
  if (typeof value !== 'string' || !path.isAbsolute(value)
    || path.resolve(value) !== value || value.includes('\0')) {
    throw fail('MCP_PODMAN_PATH_INVALID', 'Podman executable must be a normalized absolute path');
  }
  return value;
}

function validateProfile(profile) {
  if (!profile || profile.backend !== undefined && profile.backend !== 'podman-rootless'
    || profile.rootlessRequired !== true || profile.readOnlyRootRequired !== true
    || profile.noNewPrivilegesRequired !== true || profile.dropAllCapabilitiesRequired !== true
    || profile.hubDataMountsAllowed !== false || profile.runtimeSocketAllowed !== false
    || profile.network !== 'none'
    || typeof profile.image !== 'string'
    || !/@sha256:[a-f0-9]{64}$/.test(profile.image)
    || !Number.isSafeInteger(profile.memoryBytes)
    || !Number.isSafeInteger(profile.cpuQuotaMicros)
    || !Number.isSafeInteger(profile.pidsLimit)
    || !Number.isSafeInteger(profile.timeoutMs)) {
    throw fail('MCP_PODMAN_PROFILE_INVALID', 'Podman runner requires a validated, immutable, network-disabled profile');
  }
}

/**
 * Build a shell-free Podman invocation for an immutable, preloaded image.
 * No host paths, Hub data, runtime socket, credentials, or user-controlled
 * command/arguments are passed into the container. The image ENTRYPOINT is
 * the only process configuration.
 */
export function buildMcpPodmanRunSpec({
  podmanPath = '/usr/bin/podman',
  profile,
  containerName = 'agentforge-mcp-' + randomUUID(),
} = {}) {
  requireAbsoluteExecutable(podmanPath);
  validateProfile(profile);
  if (typeof containerName !== 'string'
    || !/^agentforge-mcp-[a-f0-9-]{36}$/.test(containerName)) {
    throw fail('MCP_PODMAN_CONTAINER_NAME_INVALID', 'Container name must be generated by the Hub');
  }
  const args = [
    'run', '--rm', '--interactive',
    '--name', containerName,
    '--pull=never',
    '--network=none',
    '--read-only',
    '--cap-drop=ALL',
    '--security-opt=no-new-privileges',
    '--userns=auto',
    '--user=65532:65532',
    '--pids-limit=' + String(profile.pidsLimit),
    '--memory=' + String(profile.memoryBytes),
    '--cpus=' + (profile.cpuQuotaMicros / 100_000).toFixed(2),
    '--tmpfs=/tmp:rw,noexec,nosuid,nodev,size=16m',
    '--log-driver=none',
    '--stop-timeout=2',
    profile.image,
  ];
  return Object.freeze({
    command: podmanPath,
    args: Object.freeze(args),
    shell: false,
    stdio: Object.freeze(['pipe', 'pipe', 'ignore']),
    containerName,
    timeoutMs: profile.timeoutMs,
  });
}

/**
 * Probe the actual Podman daemonless runtime before enabling any runner.
 * The probe executes only the fixed "info --format json" command and bounds
 * both execution time and captured output. It does not launch an MCP image.
 */
export async function probeMcpPodmanRootless({
  podmanPath = '/usr/bin/podman',
  spawnProcess = spawn,
  timeoutMs = 3_000,
} = {}) {
  requireAbsoluteExecutable(podmanPath);
  if (typeof spawnProcess !== 'function' || !Number.isInteger(timeoutMs)
    || timeoutMs < 250 || timeoutMs > 10_000) {
    throw new TypeError('A spawn function and bounded probe timeout are required');
  }

  return new Promise((resolve, reject) => {
    let child;
    let stdout = '';
    let settled = false;
    const finish = (error, value) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (error) reject(error);
      else resolve(value);
    };
    const timer = setTimeout(() => {
      try { child?.kill('SIGKILL'); } catch { /* best effort */ }
      finish(fail('MCP_PODMAN_PROBE_TIMEOUT', 'Podman capability probe exceeded its deadline'));
    }, timeoutMs);
    timer.unref?.();

    try {
      child = spawnProcess(podmanPath, ['info', '--format', 'json'], {
        shell: false,
        windowsHide: true,
        stdio: ['ignore', 'pipe', 'ignore'],
        env: { PATH: path.dirname(podmanPath), HOME: process.env.HOME ?? '' },
      });
    } catch {
      finish(fail('MCP_PODMAN_UNAVAILABLE', 'Podman executable could not be started'));
      return;
    }

    child.stdout?.on('data', (chunk) => {
      stdout += chunk.toString('utf8');
      if (Buffer.byteLength(stdout, 'utf8') > MAX_INFO_BYTES) {
        try { child.kill('SIGKILL'); } catch { /* best effort */ }
        finish(fail('MCP_PODMAN_PROBE_OUTPUT_LIMIT', 'Podman capability response exceeded 64 KiB'));
      }
    });
    child.once('error', () => finish(fail('MCP_PODMAN_UNAVAILABLE', 'Podman capability probe failed to start')));
    child.once('close', (code) => {
      if (settled) return;
      if (code !== 0) {
        finish(fail('MCP_PODMAN_UNAVAILABLE', 'Podman info command returned a non-zero exit status'));
        return;
      }
      let info;
      try { info = JSON.parse(stdout); } catch {
        finish(fail('MCP_PODMAN_INFO_INVALID', 'Podman returned invalid capability JSON'));
        return;
      }
      const rootless = info?.host?.security?.rootless === true
        || info?.Host?.Security?.Rootless === true;
      if (!rootless) {
        finish(fail('MCP_PODMAN_NOT_ROOTLESS', 'Podman is not running in rootless mode'));
        return;
      }
      finish(null, Object.freeze({ available: true, rootless: true }));
    });
  });
}
